unsigned int script_opcode_length(unsigned int op)
{
    if (op >= SCRIPT_OPCODE_COUNT) {
        return 0;
    }
    return lengths[op];
}

enum script_op_family script_opcode_family(unsigned int op)
{
    if (op >= SCRIPT_OPCODE_COUNT) {
        return SCRIPT_OP_ABSENT;
    }
    return (enum script_op_family)families[op];
}
