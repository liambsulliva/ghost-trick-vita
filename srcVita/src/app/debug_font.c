static renderer_texture atlas_texture;

static int character_is_in_font(char character)
{
    return character >= DEBUG_FONT_FIRST_CHARACTER && character <= DEBUG_FONT_LAST_CHARACTER;
}

int debug_font_glyph_pixel_is_set(char character, int x, int y)
{
    unsigned char column;

    if (!character_is_in_font(character)) {
        return 0;
    }
    if (x < 0 || x >= DEBUG_FONT_GLYPH_WIDTH || y < 0 || y >= DEBUG_FONT_GLYPH_HEIGHT) {
        return 0;
    }
    column = glyph_columns[character - DEBUG_FONT_FIRST_CHARACTER][x];
    return (column >> y) & 1;
}

void debug_font_fill_atlas(unsigned char *rgba_pixels, int atlas_width, int atlas_height)
{
    int glyph;
    int glyph_x;
    int glyph_y;
    int pixel_index;
    int atlas_x;
    int atlas_y;
    char character;

    memset(rgba_pixels, 0, (unsigned int)(atlas_width * atlas_height * 4));
    for (glyph = 0; glyph < GLYPH_COUNT; glyph++) {
        character = (char)(glyph + DEBUG_FONT_FIRST_CHARACTER);
        for (glyph_y = 0; glyph_y < DEBUG_FONT_GLYPH_HEIGHT; glyph_y++) {
            for (glyph_x = 0; glyph_x < DEBUG_FONT_GLYPH_WIDTH; glyph_x++) {
                if (!debug_font_glyph_pixel_is_set(character, glyph_x, glyph_y)) {
                    continue;
                }
                atlas_x = (glyph % ATLAS_COLUMNS) * DEBUG_FONT_CELL_WIDTH + glyph_x;
                atlas_y = (glyph / ATLAS_COLUMNS) * DEBUG_FONT_CELL_HEIGHT + glyph_y;
                pixel_index = (atlas_y * atlas_width + atlas_x) * 4;
                rgba_pixels[pixel_index] = 255;
                rgba_pixels[pixel_index + 1] = 255;
                rgba_pixels[pixel_index + 2] = 255;
                rgba_pixels[pixel_index + 3] = 255;
            }
        }
    }
}

int debug_font_init(void)
{
    unsigned char *pixels;

    pixels = mem_alloc(ATLAS_WIDTH * ATLAS_HEIGHT * 4);
    if (pixels == NULL) {
        return 0;
    }
    debug_font_fill_atlas(pixels, ATLAS_WIDTH, ATLAS_HEIGHT);
    atlas_texture = renderer_texture_create(pixels, ATLAS_WIDTH, ATLAS_HEIGHT);
    mem_free(pixels);
    return atlas_texture != RENDERER_NO_TEXTURE;
}

void debug_font_shutdown(void)
{
    if (atlas_texture != RENDERER_NO_TEXTURE) {
        renderer_texture_destroy(atlas_texture);
    }
    atlas_texture = RENDERER_NO_TEXTURE;
}

float debug_font_text_width(const char *text, float scale)
{
    return (float)strlen(text) * DEBUG_FONT_CELL_WIDTH * scale;
}

void debug_font_draw_text(float x, float y, float scale, struct renderer_color color, const char *text)
{
    struct renderer_rect screen_area;
    struct renderer_rect texture_area;
    int index;
    int glyph;

    screen_area.width = DEBUG_FONT_GLYPH_WIDTH * scale;
    screen_area.height = DEBUG_FONT_GLYPH_HEIGHT * scale;
    screen_area.y = y;
    texture_area.width = (float)DEBUG_FONT_GLYPH_WIDTH / ATLAS_WIDTH;
    texture_area.height = (float)DEBUG_FONT_GLYPH_HEIGHT / ATLAS_HEIGHT;
    for (index = 0; text[index] != '\0'; index++) {
        if (character_is_in_font(text[index]) && text[index] != ' ') {
            glyph = text[index] - DEBUG_FONT_FIRST_CHARACTER;
            screen_area.x = x + (float)index * DEBUG_FONT_CELL_WIDTH * scale;
            texture_area.x = (float)((glyph % ATLAS_COLUMNS) * DEBUG_FONT_CELL_WIDTH) / ATLAS_WIDTH;
            texture_area.y = (float)((glyph / ATLAS_COLUMNS) * DEBUG_FONT_CELL_HEIGHT) / ATLAS_HEIGHT;
            renderer_draw_sprite(atlas_texture, screen_area, texture_area, color);
        }
    }
}
